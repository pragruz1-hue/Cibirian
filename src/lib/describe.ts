export function productKind(p: Product): ProductKind {
  const hay = `${p.name} ${getCategory(p.category)?.name ?? ''}`;
  for (const rule of KIND_RULES) if (rule.re.test(hay)) break;
  const found = KIND_RULES.find((r) => r.re.test(hay));
  return KINDS.find((k) => k.key === (found?.key ?? 'shampoo')) ?? KINDS[0];
}

export interface ProductDescription {
  short: string;
  paragraphs: string[];
  specs: { label: string; value: string }[];
  application: string;
  kind: string;
}

function joinList(items: string[]): string {
  if (!items.length) return '';
  if (items.length === 1) return items[0];
  return `${items.slice(0, -1).join(', ')} и ${items[items.length - 1]}`;
}

export function describeProduct(p: Product): ProductDescription {
  const kind = productKind(p);
  const cat = getCategory(p.category);
  const line = p.line?.trim();
  const title = [p.brand, line].filter(Boolean).join(' ');
  const purposes = p.purpose ?? [];
  const hair = p.hairType ?? [];

  const parts: string[] = [];
  if (title) parts.push(`${title}`);
  if (p.volume) parts.push(`объём ${p.volume}`);
  const first = parts.length ? `${parts.join(', ')}.` : `${p.name}.`;

  const second =
    purposes.length > 0
      ? `Средство работает на результат: ${joinList(purposes)}.`
      : `Средство относится к категории «${cat?.name ?? kind.label}» и подходит для повседневного салонного и домашнего применения.`;

  const third =
    hair.length > 0
      ? `Рекомендовано для типов волос: ${joinList(hair)}.`
      : 'Подходит для всех типов волос при регулярном применении.';

  const short = `${kind.label} ${p.brand}${p.volume ? `, ${p.volume}` : ''}. ${
    purposes.length ? `Основные задачи — ${joinList(purposes.slice(0, 3))}.` : 'Профессиональная линия.'
  }`;

  const specs: { label: string; value: string }[] = [
    { label: 'Бренд', value: p.brand },
    ...(line ? [{ label: 'Линейка', value: line }] : []),
    { label: 'Тип средства', value: kind.label },
    ...(p.volume ? [{ label: 'Объём', value: p.volume }] : []),
    ...(purposes.length ? [{ label: 'Назначение', value: joinList(purposes) }] : []),
    ...(hair.length ? [{ label: 'Тип волос', value: joinList(hair) }] : []),
    ...(p.palette?.length ? [{ label: 'Палитра / оттенок', value: joinList(p.palette) }] : []),
    ...(cat ? [{ label: 'Раздел каталога', value: cat.name }] : []),
    { label: 'Наличие', value: p.inStock ? 'Есть в наличии' : 'Нет в наличии, под заказ' },
    { label: 'Артикул', value: `SBC-${String(p.id).padStart(6, '0')}` },
  ];

  return {
    short,
    paragraphs: [first, `${second} ${third}`, kind.about],
    specs,
    application: kind.how,
    kind: kind.label,
  };
}
